// Generates a single read-only SQL statement that reports which objects the
// migrations in supabase/*.sql expect but production does not have.
//
// Why generate instead of query the catalog and diff locally: the SQL editor is
// the only door we have (no DB connection string, service role hits PostgREST
// only). A "select everything" result would be a few hundred rows of noise in a
// browser tab; this returns just the shortfall, usually zero rows.
//
// Run: node scripts/gen-schema-diff.mjs
//
// Writes the file itself instead of printing to stdout. PowerShell 5.1's `>`
// redirect emits UTF-16LE with a BOM, which the SQL editor then has to be
// coaxed into decoding and which git treats as a binary blob.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'supabase';
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();

/** @type {Set<string>} */
const expected = new Set();

const add = (kind, name) => expected.add(`${kind}\u0000${name}`);

for (const file of files) {
  const sql = readFileSync(join(dir, file), 'utf8');

  // create table [if not exists] public.x
  for (const m of sql.matchAll(
    /create\s+table\s+(?:if\s+not\s+exists\s+)?public\.("?)([a-z0-9_]+)\1/gi,
  )) {
    add('table', m[2]);
  }

  // create [or replace] function public.x(
  for (const m of sql.matchAll(
    /create\s+(?:or\s+replace\s+)?function\s+public\.("?)([a-z0-9_]+)\1\s*\(/gi,
  )) {
    add('function', m[2]);
  }

  // create [or replace] view public.x — plpgsql bodies do not validate at
  // creation time, so a missing view is just as invisible as a missing table
  // until a user hits it.
  for (const m of sql.matchAll(
    /create\s+(?:or\s+replace\s+)?view\s+public\.("?)([a-z0-9_]+)\1/gi,
  )) {
    add('view', m[2]);
  }

  // create policy "x" on public.y
  for (const m of sql.matchAll(
    /create\s+policy\s+"?([a-z0-9_]+)"?\s+on\s+public\.("?)([a-z0-9_]+)\2/gi,
  )) {
    add('policy', `${m[3]}.${m[1]}`);
  }
}

const rows = [...expected]
  .sort()
  .map((k) => {
    const [kind, name] = k.split('\u0000');
    return `    ('${kind}', '${name}')`;
  });

const out = `-- Expected objects that production does NOT have.
-- Generated by scripts/gen-schema-diff.mjs from ${files.length} migration files.
-- Read-only. A row here is not automatically a bug: migrations legitimately
-- drop things (posts_select_public was retired on purpose), so review each line
-- before calling anything missing.
with expected(kind, name) as (
  values
${rows.join(',\n')}
),
have as (
  select 'table' as kind, tablename as name
    from pg_tables where schemaname = 'public'
  union all
  select 'view', viewname
    from pg_views where schemaname = 'public'
  union all
  select 'function', proname
    from pg_proc where pronamespace = 'public'::regnamespace
  union all
  select 'policy', tablename || '.' || policyname
    from pg_policies where schemaname = 'public'
)
select e.kind, e.name
  from expected e
  left join have h on h.kind = e.kind and h.name = e.name
 where h.name is null
 order by 1, 2;
`;

writeFileSync(join(dir, '_schema_diff.sql'), out, 'utf8');
process.stdout.write(`wrote ${join(dir, '_schema_diff.sql')} (${out.length} chars, ${expected.size} expected objects)\n`);
